use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DatabaseItem {
    pub name: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SchemaItem {
    pub name: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableItem {
    pub schema: String,
    pub name: String,
    pub kind: String, // 'BASE TABLE' or 'VIEW'
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ColumnItem {
    pub name: String,
    pub data_type: String,
    pub max_length: Option<i32>,
    pub precision: Option<i32>,
    pub scale: Option<i32>,
    pub is_nullable: bool,
    pub is_primary_key: bool,
    pub is_identity: bool,
    /// Computed columns cannot be written by an INSERT.
    pub is_computed: bool,
    /// `timestamp` / `rowversion` columns are generated by the server.
    pub is_row_version: bool,
    /// `sys.default_constraints.definition` (empty when the column has no default).
    pub default_definition: Option<String>,
    /// Column collation, which only matters for character types.
    pub collation: Option<String>,
    /// `sys.computed_columns.definition`, the expression behind a computed column.
    pub computed_expression: Option<String>,
    /// `PERSISTED` on a computed column.
    pub is_persisted: bool,
    /// Identity seed / increment, so a scripted table keeps its original numbering.
    pub identity_seed: Option<i64>,
    pub identity_increment: Option<i64>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableSchema {
    pub schema: String,
    pub name: String,
    pub kind: String, // 'BASE TABLE' or 'VIEW'
    pub columns: Vec<ColumnItem>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ForeignKeyItem {
    pub constraint_name: String,
    pub from_schema: String,
    pub from_table: String,
    pub from_column: String,
    pub to_schema: String,
    pub to_table: String,
    pub to_column: String,
}

/// One column of a constraint or index key, in key order.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct KeyColumnRef {
    pub name: String,
    pub descending: bool,
}

/// A PRIMARY KEY / UNIQUE / CHECK / DEFAULT / FOREIGN KEY constraint on one table.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableConstraintItem {
    pub name: String,
    /// `PRIMARY_KEY` | `UNIQUE` | `CHECK` | `DEFAULT` | `FOREIGN_KEY`
    pub kind: String,
    /// Key columns for PRIMARY_KEY / UNIQUE, referencing columns for FOREIGN_KEY.
    pub key_columns: Vec<KeyColumnRef>,
    /// CHECK expression, or the DEFAULT expression. `None` for key constraints.
    pub definition: Option<String>,
    /// The column a DEFAULT constraint is bound to.
    pub default_column: Option<String>,
    /// Whether the backing index of a PRIMARY KEY / UNIQUE constraint is clustered.
    pub is_clustered: Option<bool>,
    pub is_disabled: bool,
    pub is_not_trusted: bool,
    pub ref_schema: Option<String>,
    pub ref_table: Option<String>,
    /// Referenced columns of a FOREIGN KEY, aligned with `key_columns`.
    pub ref_columns: Vec<String>,
    pub on_delete: Option<String>,
    pub on_update: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IndexColumnRef {
    pub name: String,
    pub descending: bool,
    pub is_included: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableIndexItem {
    pub name: String,
    /// `CLUSTERED` | `NONCLUSTERED` | `CLUSTERED COLUMNSTORE` | `XML` | `SPATIAL` | …
    pub type_desc: String,
    pub is_unique: bool,
    /// True for the index that backs a PRIMARY KEY (listed as a constraint instead).
    pub is_primary_key: bool,
    /// True for the index that backs a UNIQUE constraint (listed as a constraint instead).
    pub is_unique_constraint: bool,
    pub is_disabled: bool,
    pub columns: Vec<IndexColumnRef>,
    pub filter_definition: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableTriggerItem {
    pub name: String,
    pub is_instead_of: bool,
    pub is_disabled: bool,
    /// `INSERT` / `UPDATE` / `DELETE` for DML triggers.
    pub events: Vec<String>,
    /// `sys.sql_modules.definition`; `None` when the caller may not read it.
    pub definition: Option<String>,
}

/// Everything the Explorer shows under one table or view node, in a single round trip.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableObjects {
    pub columns: Vec<ColumnItem>,
    pub constraints: Vec<TableConstraintItem>,
    pub indexes: Vec<TableIndexItem>,
    pub triggers: Vec<TableTriggerItem>,
}
