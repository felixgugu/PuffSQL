#!/usr/bin/env node
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Turns docs/PuffSQL-Icons/svg/*.svg into one Vue component per icon under src/components/icons/.
 *
 * The source set is already drawn on the app's grid (24 x 24, fill none, currentColor, 2px round
 * strokes), so the conversion is deliberately small: drop the fixed `width`/`height` (Tailwind
 * classes size the icon at the call site), pin the viewBox, normalise every paint to
 * `currentColor`, and namespace any `id` so two instances on one page cannot collide.
 *
 * Usage:
 *   node scripts/build-icons.mjs            # write src/components/icons/**
 *   node scripts/build-icons.mjs --check    # verify the checked-in files match the sources
 */

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(rootDir, 'docs', 'PuffSQL-Icons', 'svg');
const outDir = path.join(rootDir, 'src', 'components', 'icons');
const GRID = 24;
const GENERATED_BY = 'Generated by scripts/build-icons.mjs from docs/PuffSQL-Icons/svg — do not edit by hand.';

/** Paint values that are not colours and must survive normalisation. */
const NON_PAINT = new Set(['none', 'currentcolor', 'inherit', 'transparent', 'url']);

function isPaint(value) {
  const trimmed = value.trim().toLowerCase();
  if (!trimmed) return false;
  for (const keep of NON_PAINT) {
    if (trimmed === keep || trimmed.startsWith(`${keep}(`)) return false;
  }
  return true;
}

function toCurrentColor(attrName, value) {
  // `fill="none"`, `stroke-width="2"` and url(#…) references stay exactly as they are.
  if (attrName === 'stroke-width' || attrName === 'stroke-dasharray' || attrName === 'opacity') return value;
  if (attrName === 'fill' || attrName === 'stroke' || attrName === 'color') {
    return isPaint(value) ? 'currentColor' : value;
  }
  return value;
}

/** Attribute-aware rewrite: only paints are touched, so geometry and ids keep their own rules. */
function normaliseAttributes(markup, { prefixIds }) {
  let out = markup.replace(
    /([a-zA-Z-]+)="([^"]*)"/g,
    (match, attrName, value) => {
      if (attrName.startsWith('xmlns') || attrName === 'width' || attrName === 'height') return match;
      let next = toCurrentColor(attrName, value);
      if (prefixIds && attrName === 'id' && !next.startsWith(prefixIds)) next = `${prefixIds}${next}`;
      if (prefixIds && (attrName === 'href' || attrName === 'xlink:href')) {
        next = next.replace(/^#(.+)$/, (_, id) => `#${prefixIds}${id}`);
      }
      if (attrName === 'style') {
        next = next.replace(/(fill|stroke)\s*:\s*([^;]+)/g, (decl, prop, val) =>
          isPaint(val) ? `${prop}: currentColor` : decl
        );
      }
      return `${attrName}="${next}"`;
    }
  );
  out = out.replace(/url\(#([^)]+)\)/g, (_, id) => (prefixIds ? `url(#${prefixIds}${id})` : `url(#${id})`));
  return out;
}

/** Reads one source file into the parts the component needs. */
export function normaliseIcon(name, source) {
  const svgMatch = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/i);
  if (!svgMatch) throw new Error(`${name}: no <svg> element`);

  const [, rawAttrs, rawInner] = svgMatch;
  const attrs = {};
  for (const [, attrName, value] of rawAttrs.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
    attrs[attrName] = value;
  }

  const prefixIds = `puffsql-${name.toLowerCase()}-`;
  const viewBox = (attrs.viewBox ?? `0 0 ${GRID} ${GRID}`).trim();
  const [minX = 0, minY = 0, boxWidth = GRID, boxHeight = GRID] = viewBox
    .split(/[\s,]+/)
    .map((part) => Number(part));

  let inner = normaliseAttributes(rawInner.trim(), { prefixIds });
  if (boxWidth !== GRID || boxHeight !== GRID || minX !== 0 || minY !== 0) {
    const scale = GRID / (boxWidth || GRID);
    const transform = `translate(${-minX * scale} ${-minY * scale}) scale(${scale})`;
    inner = `<g transform="${transform}">${inner}</g>`;
  }

  // Root paints come straight from the source (fill=none, stroke=currentColor, width 2, round joins).
  const rootAttrs = {
    xmlns: 'http://www.w3.org/2000/svg',
    viewBox: `0 0 ${GRID} ${GRID}`,
  };
  for (const attrName of ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']) {
    if (attrs[attrName] !== undefined) rootAttrs[attrName] = toCurrentColor(attrName, attrs[attrName]);
  }

  return { attrs: rootAttrs, inner };
}

export function renderComponent(name, { attrs, inner }) {
  const lines = Object.entries(attrs).map(([key, value]) => `    ${key}="${value}"`);
  return [
    '<!--',
    `  ${GENERATED_BY}`,
    '-->',
    '<template>',
    '  <svg',
    ...lines,
    `  >${inner}</svg>`,
    '</template>',
    '',
  ].join('\n');
}

export function renderIndex(names) {
  const lines = names.map((name) => `export { default as ${name} } from './${name}.vue';`);
  return [`// ${GENERATED_BY}`, ...lines, ''].join('\n');
}

async function readSources() {
  const entries = await readdir(sourceDir, { withFileTypes: true });
  const names = entries
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.svg'))
    .map((entry) => entry.name.replace(/\.svg$/i, ''))
    // Code-unit order, not locale order: the generated index must be reproducible by any tool.
    .sort();
  if (names.length === 0) throw new Error(`no SVG sources in ${sourceDir}`);

  const files = new Map();
  for (const name of names) {
    const source = await readFile(path.join(sourceDir, `${name}.svg`), 'utf-8');
    files.set(`${name}.vue`, renderComponent(name, normaliseIcon(name, source)));
  }
  files.set('index.ts', renderIndex(names));
  return { names, files };
}

async function main() {
  const check = process.argv.includes('--check');
  const { names, files } = await readSources();
  const drift = [];

  if (!check) await mkdir(outDir, { recursive: true });
  const existing = existsSync(outDir)
    ? (await readdir(outDir)).filter((name) => name.endsWith('.vue') || name === 'index.ts')
    : [];

  for (const [fileName, contents] of files) {
    const target = path.join(outDir, fileName);
    if (check) {
      const current = existsSync(target) ? await readFile(target, 'utf-8') : null;
      if (current !== contents) drift.push(fileName);
    } else {
      await writeFile(target, contents, 'utf-8');
    }
  }

  for (const fileName of existing) {
    if (!files.has(fileName)) drift.push(`${fileName} (stale)`);
  }

  if (check && drift.length > 0) {
    console.error(`icon components out of date (${drift.length}):`);
    for (const fileName of drift) console.error(`  - ${fileName}`);
    console.error('run: npm run icons:build');
    process.exitCode = 1;
    return;
  }

  const verb = check ? 'verified' : 'wrote';
  console.log(`icons: ${verb} ${names.length} components + index.ts in src/components/icons/`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
