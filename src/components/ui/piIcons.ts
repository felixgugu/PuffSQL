/** Resolves a PrimeIcons class name (e.g. `pi pi-play`) to a lucide component. */
export function piIcon(name: string | undefined | null): Component | undefined {
  if (!name) return undefined;
  const key = name
    .split(/\s+/)
    .filter((part) => part.startsWith('pi-'))
    .join(' ');
  return PI_ICON_COMPONENTS[key];
}
