export type SchemaObjectType =
  | 'database'
  | 'schema'
  | 'table'
  | 'view'
  | 'column'
  | 'constraint'
  | 'index'
  | 'trigger';

export interface DatabaseItem {
  name: string;
}

export interface SchemaItem {
  name: string;
}

export interface TableItem {
  schema: string;
  name: string;
  kind: string; // 'BASE TABLE' | 'VIEW'
}

export interface RoutineItem {
  schema: string;
  name: string;
  kind: 'PROCEDURE' | 'FUNCTION';
}

export interface ColumnItem {
  name: string;
  dataType: string;
  maxLength?: number | null;
  precision?: number | null;
  scale?: number | null;
  isNullable: boolean;
  isPrimaryKey: boolean;
  isIdentity: boolean;
  /** Computed columns cannot be written by an INSERT. */
  isComputed?: boolean;
  /** `timestamp` / `rowversion` columns are generated by the server. */
  isRowVersion?: boolean;
  /** `sys.default_constraints.definition` — absent when the column has no default. */
  defaultDefinition?: string | null;
  collation?: string | null;
  /** The expression behind a computed column. */
  computedExpression?: string | null;
  /** `PERSISTED` on a computed column. */
  isPersisted?: boolean;
  identitySeed?: number | null;
  identityIncrement?: number | null;
}

export interface TableSchema {
  schema: string;
  name: string;
  kind: string; // 'BASE TABLE' | 'VIEW'
  columns: ColumnItem[];
}

export interface ForeignKeyItem {
  constraintName: string;
  fromSchema: string;
  fromTable: string;
  fromColumn: string;
  toSchema: string;
  toTable: string;
  toColumn: string;
}

/** One column of a constraint or index key, in key order. */
export interface KeyColumnRef {
  name: string;
  descending: boolean;
}

export type ConstraintKind = 'PRIMARY_KEY' | 'UNIQUE' | 'CHECK' | 'DEFAULT' | 'FOREIGN_KEY';

export interface TableConstraintItem {
  name: string;
  kind: ConstraintKind;
  /** Key columns (PRIMARY_KEY / UNIQUE) or referencing columns (FOREIGN_KEY). */
  keyColumns: KeyColumnRef[];
  /** CHECK predicate or DEFAULT expression; null for key constraints. */
  definition: string | null;
  /** The column a DEFAULT constraint is bound to. */
  defaultColumn: string | null;
  /** Whether the backing index of a PRIMARY KEY / UNIQUE constraint is clustered. */
  isClustered: boolean | null;
  isDisabled: boolean;
  isNotTrusted: boolean;
  refSchema: string | null;
  refTable: string | null;
  /** Referenced columns of a FOREIGN KEY, aligned with `keyColumns`. */
  refColumns: string[];
  onDelete: string | null;
  onUpdate: string | null;
}

export interface IndexColumnRef {
  name: string;
  descending: boolean;
  isIncluded: boolean;
}

export interface TableIndexItem {
  name: string;
  /** `CLUSTERED` | `NONCLUSTERED` | `CLUSTERED COLUMNSTORE` | `XML` | `SPATIAL` | … */
  typeDesc: string;
  isUnique: boolean;
  /** True for the index backing a PRIMARY KEY / UNIQUE constraint (listed as a constraint). */
  isPrimaryKey: boolean;
  isUniqueConstraint: boolean;
  isDisabled: boolean;
  columns: IndexColumnRef[];
  filterDefinition: string | null;
}

export interface TableTriggerItem {
  name: string;
  isInsteadOf: boolean;
  isDisabled: boolean;
  /** `INSERT` / `UPDATE` / `DELETE` for DML triggers. */
  events: string[];
  /** `sys.sql_modules.definition`; null when the caller may not read it. */
  definition: string | null;
}

/** Everything the Explorer lists under one table or view node. */
export interface TableObjects {
  columns: ColumnItem[];
  constraints: TableConstraintItem[];
  indexes: TableIndexItem[];
  triggers: TableTriggerItem[];
}

export interface SchemaTreeNode {
  id: string;
  label: string;
  type: SchemaObjectType;
  children?: SchemaTreeNode[];
  isLoaded?: boolean;
  metadata?: Record<string, unknown>;
}
